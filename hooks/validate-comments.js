#!/usr/bin/env node

const fs = require('fs');

let payload;
try { payload = JSON.parse(fs.readFileSync(0, 'utf8')); } catch { process.exit(0); }

const toolName = payload.tool_name || '';
const toolInput = payload.tool_input || {};
const filePath = toolInput.file_path || '';

const SOURCE_FILE = /\.(js|jsx|mjs|cjs|ts|tsx|kt|kts|java|swift|py|rb|go|rs|php|c|cc|cpp|cxx|h|hpp|hh|cs|scala|dart|m|mm|vue|svelte|sql|sh|bash|zsh|gradle|groovy)$/i;
const GENERATED_DIRECTORY = /(^|\/)(node_modules|dist|build|out|target|vendor|\.next|\.nuxt|coverage)\//;
const GENERATED_FILENAME = /\.(min|generated|gen|freezed|g|pb|pb2)\.[a-z]+$/i;
const GENERATED_MARKER = /(?:generated code|code generated|do not edit|do not modify|@generated\b|autogenerated\b)/i;

if (!SOURCE_FILE.test(filePath)) process.exit(0);
if (GENERATED_DIRECTORY.test(filePath) || GENERATED_FILENAME.test(filePath)) process.exit(0);

const writtenContent =
  toolName === 'Write' ? (toolInput.content || '')
  : toolName === 'Edit' ? (toolInput.new_string || '')
  : '';
if (!writtenContent.trim()) process.exit(0);

let settings = {};
try { settings = JSON.parse(fs.readFileSync("docs/basics/.alpha-sdlc.json", "utf8")); } catch {}
const allowLicenseHeader = settings.allowLicenseHeader === true;
const allowPublicApiDocstrings = settings.allowPublicApiDocstrings === true;
const LICENSE_TEXT = /copyright|license|licence|spdx-license-identifier|all rights reserved/i;

const lines = writtenContent.split(/\r?\n/);
if (GENERATED_MARKER.test(lines.slice(0, 5).join('\n'))) process.exit(0);

const extension = (filePath.match(/\.([^.]+)$/) || [, ''])[1].toLowerCase();
const HASH_COMMENT_LANGUAGES = ['py', 'rb', 'sh', 'bash', 'zsh', 'gradle', 'groovy'];
const DASH_COMMENT_LANGUAGES = ['sql'];
const MARKUP_COMMENT_LANGUAGES = ['vue', 'svelte'];

const MACHINE_DIRECTIVE = new RegExp(
  '^\\s*(?:' +
    '@?ts-(?:ignore|expect-error|nocheck|check)|' +
    'eslint(?:-disable|-enable|-env)?[\\w-]*\\b|globals\\s|jshint\\s|jslint\\s|tslint:|' +
    'prettier-ignore|biome-ignore|@formatter:(?:on|off)|' +
    '(?:istanbul|c8|v8|coverage)\\s+ignore|noinspection|deno-lint-ignore|' +
    'swiftlint:|ktlint-disable|detekt:|' +
    'noqa|type:\\s*ignore|pylint:|mypy:|ruff:|flake8:|pragma:|fmt:\\s*(?:on|off)|nosec|bandit\\b|' +
    'go:[a-z]+|\\+build\\b|nolint|' +
    'phpcs:|phpstan-|psalm-|codingStandardsIgnore|' +
    'ignore:\\s|ignore_for_file:|' +
    'sourceMappingURL|sourceURL' +
  ')',
  'i'
);

const HEREDOC_LANGUAGES = ['sh', 'bash', 'zsh'];
const HEREDOC_OPENER = /<<-?\s*(['"]?)([A-Za-z_][A-Za-z0-9_]*)\1/;

function maskStringLiterals(sourceLines) {
  const maskedLines = [];
  let openTemplateLiteral = false;
  let heredocTerminator = null;

  for (const sourceLine of sourceLines) {
    if (heredocTerminator !== null) {
      if (sourceLine.trim() === heredocTerminator) {
        heredocTerminator = null;
        maskedLines.push(sourceLine);
      } else {
        maskedLines.push('x'.repeat(sourceLine.length));
      }
      continue;
    }

    let maskedLine = '';
    let openQuote = openTemplateLiteral ? '`' : '';
    let index = 0;
    while (index < sourceLine.length) {
      const character = sourceLine[index];
      if (character === '\\' && index + 1 < sourceLine.length) {
        maskedLine += openQuote ? openQuote + openQuote : sourceLine.slice(index, index + 2);
        index += 2;
        continue;
      }
      if (openQuote) {
        maskedLine += character === openQuote ? character : openQuote;
        if (character === openQuote) openQuote = '';
        index++;
        continue;
      }
      if (character === '"' || character === "'" || character === '`') openQuote = character;
      maskedLine += character;
      index++;
    }

    openTemplateLiteral = openQuote === '`';
    maskedLines.push(maskedLine);

    if (HEREDOC_LANGUAGES.includes(extension)) {
      const heredocOpener = sourceLine.match(HEREDOC_OPENER);
      if (heredocOpener) heredocTerminator = heredocOpener[2];
    }
  }

  return maskedLines;
}

const REGEX_LITERAL_CAN_START_AFTER = /[=(,:[!&|?{};+\-*%~^<>]/;

function endOfRegexLiteral(line, startIndex) {
  let insideCharacterClass = false;
  for (let index = startIndex + 1; index < line.length; index++) {
    const character = line[index];
    if (character === '\\') { index++; continue; }
    if (character === '[') insideCharacterClass = true;
    else if (character === ']') insideCharacterClass = false;
    else if (character === '/' && !insideCharacterClass) return index;
  }
  return -1;
}

function findCommentStarts(line, previousSignificantCharacter) {
  let lastSignificantCharacter = previousSignificantCharacter;
  for (let index = 0; index < line.length; index++) {
    const character = line[index];
    if (character === '\\') { index++; continue; }
    if (character === '/') {
      const nextCharacter = line[index + 1];
      if (nextCharacter === '/') return { lineComment: index, blockComment: -1, lastSignificantCharacter };
      if (nextCharacter === '*') return { lineComment: -1, blockComment: index, lastSignificantCharacter };
      if (lastSignificantCharacter === '' || REGEX_LITERAL_CAN_START_AFTER.test(lastSignificantCharacter)) {
        const regexEnd = endOfRegexLiteral(line, index);
        if (regexEnd !== -1) { index = regexEnd; lastSignificantCharacter = '/'; continue; }
      }
    }
    if (!/\s/.test(character)) lastSignificantCharacter = character;
  }
  return { lineComment: -1, blockComment: -1, lastSignificantCharacter };
}

const maskedLines = maskStringLiterals(lines);
const findings = [];

function record(rawText, lineNumber) {
  const body = rawText
    .replace(/^\s*(?:\/\/+|\/\*+|#+|--|<!--|\*+)/, '')
    .replace(/(?:\*\/|-->)\s*$/, '');
  if (MACHINE_DIRECTIVE.test(body)) return;
  findings.push({
    line: lineNumber,
    text: rawText.trim().replace(/\s+/g, ' ').slice(0, 90),
    isDocComment: /^\s*(?:\/\*\*|\/\/\/)/.test(rawText),
  });
}

let significantCharacterCarry = '';

maskedLines.forEach((maskedLine, index) => {
  const rawLine = lines[index];
  const lineNumber = index + 1;

  const { lineComment, blockComment, lastSignificantCharacter } = findCommentStarts(maskedLine, significantCharacterCarry);
  significantCharacterCarry = lastSignificantCharacter;
  if (lineComment !== -1) record(rawLine.slice(lineComment), lineNumber);
  if (blockComment !== -1) record(rawLine.slice(blockComment), lineNumber);

  if (MARKUP_COMMENT_LANGUAGES.includes(extension)) {
    const markupCommentOpen = maskedLine.indexOf('<!--');
    if (markupCommentOpen !== -1) record(rawLine.slice(markupCommentOpen), lineNumber);
  }

  if (HASH_COMMENT_LANGUAGES.includes(extension)) {
    const hashMatch = maskedLine.match(/(?:^|\s)#(?!!)/);
    if (hashMatch) record(rawLine.slice(maskedLine.indexOf('#', hashMatch.index)), lineNumber);
  }

  if (DASH_COMMENT_LANGUAGES.includes(extension)) {
    const dashMatch = maskedLine.match(/(?:^|\s)--(?!-)/);
    if (dashMatch) record(rawLine.slice(maskedLine.indexOf('--', dashMatch.index)), lineNumber);
  }
});

if (extension === 'py') {
  for (const match of writtenContent.matchAll(/("""|''')[\s\S]*?\1/g)) {
    const lineStart = writtenContent.lastIndexOf('\n', match.index) + 1;
    const textBeforeQuotes = writtenContent.slice(lineStart, match.index);
    if (!/^[ \t]*[rubfRUBF]{0,2}$/.test(textBeforeQuotes)) continue;
    findings.push({
      line: writtenContent.slice(0, match.index).split('\n').length,
      text: match[0].trim().replace(/\s+/g, ' ').slice(0, 90),
      isDocComment: true,
    });
  }
}

const keptFindings = findings.filter((finding) => {
  if (allowLicenseHeader && finding.line <= 15 && LICENSE_TEXT.test(finding.text)) return false;
  if (allowPublicApiDocstrings && finding.isDocComment) return false;
  return true;
});
findings.length = 0;
findings.push(...keptFindings);

if (!findings.length) process.exit(0);

const firstFinding = findings[0];
const remainingCount = findings.length > 1 ? ` (+${findings.length - 1} more in this change)` : '';

process.stderr.write(
  `Comment in source code at line ${firstFinding.line}: "${firstFinding.text}"${remainingCount}\n` +
  `Per principles.md, code carries ZERO comments — no explanatory prose, no doc comments ` +
  `(JSDoc/KDoc/Javadoc/Python docstrings), no license headers, no banners, no provenance. ` +
  `Delete it and let names and structure carry the meaning instead: rename the variable, extract ` +
  `and name the function, introduce a named constant for the magic number, or name the predicate ` +
  `(retryAfterUpstreamRateLimit() beats a comment explaining the retry). ` +
  `If the WHY genuinely cannot live in a name — an upstream bug, a regulatory threshold, a ` +
  `benchmark behind a constant — put it in the commit message or PR description, where history ` +
  `belongs and cannot rot beside code that changed. ` +
  `Only machine directives are allowed (eslint-disable, @ts-expect-error, # noqa, # type: ignore, ` +
  `# pragma: no cover, //go:build, swiftlint:disable, shebang) — a compiler, linter or coverage ` +
  `tool acts on those and no rename replaces them.\n`
);
process.exit(2);
